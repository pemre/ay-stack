describe("Content Graph — Property 14: Legacy adapter fidelity", () => {
  /**
   * contentGraphToLegacyIndex produces a ContentIndex with the same number
   * of entries as graph.nodes.
   *
   * **Validates: Requirements 7.1, 7.2, 7.3, 7.4, 7.5**
   */
  it("produces the same number of entries as graph.nodes", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");
        const index = contentGraphToLegacyIndex(graph);
        expect(Object.keys(index).length).toBe(Object.keys(graph.nodes).length);
      }),
      { numRuns: 200 },
    );
  });

  /**
   * Each entry's id, title, and tags match the source node.
   *
   * **Validates: Requirements 7.1, 7.2, 7.3, 7.4, 7.5**
   */
  it("each entry's id, title, and tags match the source node", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");
        const index = contentGraphToLegacyIndex(graph);

        for (const node of Object.values(graph.nodes)) {
          const entry = index[node.id];
          expect(entry).toBeDefined();
          expect(entry.id).toBe(node.id);
          expect(entry.title).toBe(node.title);
          expect(entry.tags).toEqual(node.tags);
        }
      }),
      { numRuns: 200 },
    );
  });

  /**
   * _isHeader is false for all entries.
   *
   * **Validates: Requirements 7.1, 7.2, 7.3, 7.4, 7.5**
   */
  it("_isHeader is false for all entries", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");
        const index = contentGraphToLegacyIndex(graph);

        for (const entry of Object.values(index)) {
          expect(entry._isHeader).toBe(false);
        }
      }),
      { numRuns: 200 },
    );
  });

  /**
   * _path equals the node's relativePath.
   *
   * **Validates: Requirements 7.1, 7.2, 7.3, 7.4, 7.5**
   */
  it("_path equals relativePath for every entry", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");
        const index = contentGraphToLegacyIndex(graph);

        for (const node of Object.values(graph.nodes)) {
          expect(index[node.id]._path).toBe(node.relativePath);
        }
      }),
      { numRuns: 200 },
    );
  });

  /**
   * Markdown frontmatter fields are spread into the entry.
   *
   * **Validates: Requirements 7.1, 7.2, 7.3, 7.4, 7.5**
   */
  it("spreads markdown frontmatter fields into the entry", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");
        const index = contentGraphToLegacyIndex(graph);

        for (const node of Object.values(graph.nodes)) {
          if (node.frontmatter) {
            const entry = index[node.id];
            for (const [key, value] of Object.entries(node.frontmatter)) {
              // Core fields (id, title, tags, _isHeader, _path) are overridden
              // after the spread, so skip checking those
              if (["id", "title", "tags", "_isHeader", "_path"].includes(key)) {
                continue;
              }
              expect(entry[key]).toEqual(value);
            }
          }
        }
      }),
      { numRuns: 200 },
    );
  });

  /**
   * getContentBody returns the node's body when it exists, null otherwise.
   *
   * **Validates: Requirements 7.1, 7.2, 7.3, 7.4, 7.5**
   */
  it("getContentBody returns body for existing nodes and null for missing ones", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");

        for (const node of Object.values(graph.nodes)) {
          const body = getContentBody(graph, node.id);
          expect(body).toBe(node.body ?? null);
        }

        // Non-existent ID returns null
        expect(getContentBody(graph, "nonexistent-id-xyz")).toBeNull();
      }),
      { numRuns: 200 },
    );
  });
});
