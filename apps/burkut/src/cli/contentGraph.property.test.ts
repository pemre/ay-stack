/*  Shared arbitraries for buildContentGraph property tests           */
/* ------------------------------------------------------------------ */

const arbContentType: fc.Arbitrary<ContentType> = fc.constantFrom(
  "markdown",
  "image",
  "video",
  "audio",
);

const arbIsoDate = fc
  .record({
    year: fc.integer({ min: 1900, max: 2099 }),
    month: fc.integer({ min: 1, max: 12 }),
    day: fc.integer({ min: 1, max: 28 }),
  })
  .map(
    ({ year, month, day }) =>
      `${String(year).padStart(4, "0")}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`,
  );

const arbOptionalDate = fc.option(arbIsoDate, { nil: null });

const arbFrontmatter = fc.option(
  fc.record({
    title: fc.option(fc.string({ minLength: 0, maxLength: 30 }), { nil: undefined }),
    tags: fc.option(fc.array(fc.string({ minLength: 1, maxLength: 15 }), { maxLength: 5 }), {
      nil: undefined,
    }),
  }),
  { nil: null },
);

/** Build an array of ScannedFile with unique relative paths. */
const arbScannedFiles: fc.Arbitrary<ScannedFile[]> = fc
  .uniqueArray(
    arbStem.map((s) => s.toLowerCase()),
    { minLength: 0, maxLength: 30, comparator: (a, b) => a === b },
  )
  .chain((stems) =>
    fc.tuple(
      ...stems.map((stem) =>
        fc
          .tuple(
            arbContentType,
            arbOptionalDate,
            arbFrontmatter,
            fc.option(fc.string(), { nil: null }),
          )
          .map(([contentType, date, frontmatter, body]): ScannedFile => {
            const ext =
              contentType === "markdown"
                ? ".md"
                : contentType === "image"
                  ? ".jpg"
                  : contentType === "video"
                    ? ".mp4"
                    : ".mp3";
            return {
              absolutePath: `/tmp/test/${stem}${ext}`,
              relativePath: `${stem}${ext}`,
              contentType,
              date,
              frontmatter: frontmatter as Record<string, unknown> | null,
              body: contentType === "markdown" ? (body ?? "") : null,
            };
          }),
      ),
    ),
  );

