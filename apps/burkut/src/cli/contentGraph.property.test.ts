describe("Content Graph — Property 8: Graph partition", () => {
  /**
   * Every node appears in exactly one of days[].nodes or undated — never both, never neither.
   *
   * **Validates: Requirements 5.2, 5.3**
   */
  it("every node is in exactly one partition: a day bucket or undated", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");

        const datedIds = new Set<string>();
        for (const day of graph.days) {
          for (const node of day.nodes) {
            datedIds.add(node.id);
          }
        }

        const undatedIds = new Set(graph.undated.map((n) => n.id));

        for (const id of Object.keys(graph.nodes)) {
          const inDated = datedIds.has(id);
          const inUndated = undatedIds.has(id);

          // Exactly one must be true
          expect(inDated || inUndated).toBe(true);
          expect(inDated && inUndated).toBe(false);
        }
      }),
      { numRuns: 200 },
    );
  });

  /**
   * Dated nodes appear in day buckets, undated nodes appear in graph.undated.
   *
   * **Validates: Requirements 5.2, 5.3**
   */
  it("dated nodes are in day buckets and undated nodes are in graph.undated", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");

        const datedIds = new Set<string>();
        for (const day of graph.days) {
          for (const node of day.nodes) {
            datedIds.add(node.id);
          }
        }

        for (const node of Object.values(graph.nodes)) {
          if (node.date !== null) {
            expect(datedIds.has(node.id)).toBe(true);
          } else {
            expect(graph.undated.some((u) => u.id === node.id)).toBe(true);
          }
        }
      }),
      { numRuns: 200 },
    );
  });

  /**
   * No extra nodes exist in partitions that aren't in graph.nodes.
   *
   * **Validates: Requirements 5.2, 5.3**
   */
  it("no phantom nodes in partitions outside graph.nodes", () => {
    fc.assert(
      fc.property(arbScannedFiles, (files) => {
        const graph = buildContentGraph(files, "/tmp/test");
        const allIds = new Set(Object.keys(graph.nodes));

        for (const day of graph.days) {
          for (const node of day.nodes) {
            expect(allIds.has(node.id)).toBe(true);
          }
        }
        for (const node of graph.undated) {
          expect(allIds.has(node.id)).toBe(true);
        }
      }),
      { numRuns: 200 },
    );
  });
});

