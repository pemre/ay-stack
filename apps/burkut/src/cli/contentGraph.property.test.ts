import fc from "fast-check";
import { describe, expect, it } from "vitest";
import type { ContentType, ScannedFile } from "../shared/types.ts";
import { buildContentGraph, deriveTitle, filePathToId } from "./contentGraph.ts";

/**
 * Property-based tests for ID generation and title derivation.
 *
 * Tests Properties 10 and 11 from the design document.
 */

/** Arbitrary for a simple filename stem (no dots, no slashes, no spaces). */
const arbStem = fc
  .stringMatching(/^[a-zA-Z][a-zA-Z0-9_-]*$/)
  .filter((s) => s.length >= 1 && s.length <= 30);

/** Arbitrary for a file extension. */
const arbExt = fc.constantFrom(".md", ".jpg", ".png", ".mp4", ".mp3");

/** Arbitrary for a valid YYYY-MM-DD date string. */
const arbDatePrefix = fc
  .record({
    year: fc.integer({ min: 1900, max: 2099 }),
    month: fc.integer({ min: 1, max: 12 }),
    day: fc.integer({ min: 1, max: 28 }),
  })
  .map(
    ({ year, month, day }) =>
      `${String(year).padStart(4, "0")}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`,
  );

/** Arbitrary for an optional directory prefix (no trailing slash for empty). */
const arbDirSegment = fc
  .stringMatching(/^[a-zA-Z][a-zA-Z0-9_-]*$/)
  .filter((s) => s.length >= 1 && s.length <= 20);

describe("Content Graph — Property 10: ID uniqueness and generation", () => {
  /**
   * For any set of files with distinct relative paths, filePathToId produces unique IDs.
   *
   * **Validates: Requirements 5.7, 12.1, 12.3**
   */
  it("produces unique IDs for distinct relative paths", () => {
    fc.assert(
      fc.property(
        fc.uniqueArray(
          fc
            .tuple(arbDirSegment, arbStem, arbExt)
            .map(([dir, stem, ext]) => `${dir}/${stem}${ext}`),
          {
            minLength: 2,
            maxLength: 20,
            comparator: (a, b) => filePathToId(a) === filePathToId(b),
          },
        ),
        (paths) => {
          const ids = paths.map((p) => filePathToId(p));
          const uniqueIds = new Set(ids);
          expect(uniqueIds.size).toBe(paths.length);
        },
      ),
      { numRuns: 300 },
    );
  });

  /**
   * The ID is generated by stripping the extension, replacing `/` with `--`,
   * replacing spaces with `-`, and lowercasing.
   *
   * **Validates: Requirements 5.7, 12.1, 12.3**
   */
  it("strips extension, replaces / with --, replaces spaces with -, and lowercases", () => {
    fc.assert(
      fc.property(arbStem, arbExt, (stem, ext) => {
        const relativePath = `${stem}${ext}`;
        const id = filePathToId(relativePath);

        // No extension in the ID
        expect(id).not.toContain(ext);
        // Lowercased
        expect(id).toBe(id.toLowerCase());
        // No slashes
        expect(id).not.toContain("/");
        // No spaces
        expect(id).not.toMatch(/\s/);
      }),
      { numRuns: 300 },
    );
  });

  /**
   * Path separators are replaced with `--` in the ID.
   *
   * **Validates: Requirements 5.7, 12.1**
   */
  it("replaces path separators with --", () => {
    fc.assert(
      fc.property(arbDirSegment, arbStem, arbExt, (dir, stem, ext) => {
        const relativePath = `${dir}/${stem}${ext}`;
        const id = filePathToId(relativePath);

        expect(id).toContain("--");
        expect(id).toBe(`${dir}--${stem}`.toLowerCase());
      }),
      { numRuns: 300 },
    );
  });

  /**
   * Spaces in filenames are replaced with `-`.
   *
   * **Validates: Requirements 5.7, 12.1**
   */
  it("replaces spaces with hyphens", () => {
    const id = filePathToId("2025-03-15 journal entry.md");
    expect(id).toBe("2025-03-15-journal-entry");
  });
});

describe("Content Graph — Property 11: Title derivation priority", () => {
  /**
   * For any file with a non-empty frontmatter.title, the derived title equals
   * that frontmatter value (trimmed).
   *
   * **Validates: Requirements 5.8, 12.2**
   */
  it("uses frontmatter.title when present and non-empty", () => {
    fc.assert(
      fc.property(
        fc.string({ minLength: 1, maxLength: 50 }).filter((s) => s.trim().length > 0),
        arbStem,
        arbExt,
        (title, stem, ext) => {
          const relativePath = `${stem}${ext}`;
          const frontmatter = { title };
          const result = deriveTitle(relativePath, frontmatter);
          expect(result).toBe(title.trim());
        },
      ),
      { numRuns: 300 },
    );
  });

  /**
   * For any file without a frontmatter title, the derived title is the filename
   * with extension, date prefix, and separators stripped.
   *
   * **Validates: Requirements 5.8, 12.2**
   */
  it("derives title from filename when no frontmatter title exists", () => {
    fc.assert(
      fc.property(arbStem, arbExt, (stem, ext) => {
        const relativePath = `some-dir/${stem}${ext}`;
        const result = deriveTitle(relativePath, null);

        // Should not contain the extension
        expect(result).not.toContain(ext);
        // Should be non-empty
        expect(result.length).toBeGreaterThan(0);
      }),
      { numRuns: 300 },
    );
  });

  /**
   * Date prefixes are stripped from the filename when deriving the title.
   *
   * **Validates: Requirements 5.8, 12.2**
   */
  it("strips YYYY-MM-DD date prefix from filename", () => {
    fc.assert(
      fc.property(arbDatePrefix, arbStem, arbExt, (dateStr, stem, ext) => {
        const relativePath = `${dateStr}-${stem}${ext}`;
        const result = deriveTitle(relativePath, null);

        // The date prefix should not appear in the title
        expect(result).not.toMatch(/^\d{4}-\d{2}-\d{2}/);
      }),
      { numRuns: 300 },
    );
  });

  /**
   * Underscores and hyphens in the filename are replaced with spaces in the title.
   *
   * **Validates: Requirements 5.8, 12.2**
   */
  it("replaces underscores and hyphens with spaces", () => {
    const result = deriveTitle("my_cool-file.md", null);
    expect(result).toBe("my cool file");
  });

  /**
   * Frontmatter title takes priority even when filename has a date prefix.
   *
   * **Validates: Requirements 5.8, 12.2**
   */
  it("frontmatter title takes priority over filename derivation", () => {
    fc.assert(
      fc.property(
        fc.string({ minLength: 1, maxLength: 50 }).filter((s) => s.trim().length > 0),
        arbDatePrefix,
        arbStem,
        arbExt,
        (title, dateStr, stem, ext) => {
          const relativePath = `${dateStr}-${stem}${ext}`;
          const frontmatter = { title };
          const result = deriveTitle(relativePath, frontmatter);
          expect(result).toBe(title.trim());
        },
      ),
      { numRuns: 300 },
    );
  });

  /**
   * Empty or whitespace-only frontmatter.title falls back to filename derivation.
   *
   * **Validates: Requirements 5.8, 12.2**
   */
  it("falls back to filename when frontmatter.title is empty or whitespace", () => {
    fc.assert(
      fc.property(
        fc.constantFrom("", "   ", "\t", "\n"),
        arbStem,
        arbExt,
        (emptyTitle, stem, ext) => {
          const relativePath = `${stem}${ext}`;
          const frontmatter = { title: emptyTitle };
          const result = deriveTitle(relativePath, frontmatter);

          // Should derive from filename, not use the empty title
          expect(result.length).toBeGreaterThan(0);
          expect(result).not.toBe(emptyTitle);
        },
      ),
      { numRuns: 200 },
    );
  });
});

