/**
 * @ay/ui-library token build — derives dist/ from src/tokens/.
 *
 * Five steps, per the ui-library token component contract:
 *   1. read src/tokens/core.css      -> emit dist/core.css   (@theme static -> :root)
 *   2. copy src/tokens/core.css      -> theme core text      (verbatim, keeps @theme static)
 *   3. copy src/tokens/semantic.css  -> emit dist/semantic.css
 *   4. concat (1) + (3)       -> emit dist/tokens.css  // plain entry
 *   5. concat (2) + (3)       -> emit dist/theme.css   // Tailwind entry
 *
 * The @theme -> :root rewrite is the ONLY transformation. Values are never
 * touched, which is what makes the plain and Tailwind paths provably equivalent
 * (Property 8) and the computed-value baseline hold (Property 1).
 *
 * Step 2's verbatim copy is held in memory rather than written to a separate
 * dist file: no exports subpath targets it, so emitting it would only add an
 * unreferenced file to the published tarball. The four emitted artifacts are
 * exactly the four the exports map names.
 *
 * Entries are concatenated rather than composed with @import so the published
 * files resolve with no import graph at all — a raw <link> tag works.
 *
 * No dependencies. Plain Node ESM.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = dirname(dirname(fileURLToPath(import.meta.url)));
const SRC = join(PKG, "src", "tokens");
const DIST = join(PKG, "dist");

/** Strip comments so counting and at-rule checks see declarations only. */
function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

/**
 * Body of the first block whose prelude matches `preludeRe`, by brace matching.
 * Returns null when no such block exists.
 */
function blockBody(css, preludeRe) {
  const match = preludeRe.exec(css);
  if (!match) return null;
  const open = css.indexOf("{", match.index);
  if (open === -1) return null;
  let depth = 1;
  let i = open + 1;
  while (i < css.length && depth > 0) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") depth--;
    i++;
  }
  return css.slice(open + 1, depth === 0 ? i - 1 : css.length);
}

/** Names of the custom properties declared directly in a block body. */
function declaredNames(body) {
  const names = [];
  const re = /(--[A-Za-z0-9_-]+)\s*:/g;
  let m = re.exec(body);
  while (m !== null) {
    names.push(m[1]);
    m = re.exec(body);
  }
  return names;
}

function fail(message) {
  throw new Error(`[@ay/ui-library token build] ${message}`);
}

// ── Step 1 ────────────────────────────────────────────────────────────────────
const coreSource = readFileSync(join(SRC, "core.css"), "utf-8");

if (!/@theme\s+static\b/.test(stripComments(coreSource))) {
  fail(
    "src/tokens/core.css must declare `@theme static`. Without `static` Tailwind emits " +
      "only the theme variables it sees used as utilities, and these tokens are " +
      "consumed through hand-written var() references, so they would vanish.",
  );
}

const corePlain = coreSource.replace(/@theme\b[^{]*\{/g, ":root {");

// ── Step 2 ────────────────────────────────────────────────────────────────────
const coreTheme = coreSource;

// ── Step 3 ────────────────────────────────────────────────────────────────────
const semantic = readFileSync(join(SRC, "semantic.css"), "utf-8");

// ── The count assertion ───────────────────────────────────────────────────────
// A missing `static`, a mangled at-rule, or a rewrite that lost a block must
// fail loudly here rather than silently shipping a stylesheet with fewer tokens.
const declaredCore = declaredNames(blockBody(stripComments(coreSource), /@theme\b[^{]*/) ?? "");
const emittedCore = declaredNames(blockBody(stripComments(corePlain), /:root\b[^{]*/) ?? "");

if (declaredCore.length === 0) fail("no core tokens found in src/tokens/core.css");
if (emittedCore.length !== declaredCore.length) {
  fail(
    "core token count changed during the @theme -> :root rewrite: " +
      declaredCore.length +
      " declared, " +
      emittedCore.length +
      " emitted into :root. Missing: " +
      declaredCore.filter((n) => !emittedCore.includes(n)).join(", "),
  );
}
if (/@theme\b/.test(stripComments(corePlain))) fail("dist/core.css still carries an @theme rule");

// ── Steps 4 and 5 ─────────────────────────────────────────────────────────────
const banner =
  "/* Generated by scripts/build-tokens-css.mjs from src/tokens/. Do not edit — edit\n" +
  "   src/tokens/core.css or src/tokens/semantic.css instead. */\n\n";

const tokens = `${banner + corePlain}\n${semantic}`;
const theme = `${banner + coreTheme}\n${semantic}`;

mkdirSync(DIST, { recursive: true });
writeFileSync(join(DIST, "core.css"), banner + corePlain);
writeFileSync(join(DIST, "semantic.css"), banner + semantic);
writeFileSync(join(DIST, "tokens.css"), tokens);
writeFileSync(join(DIST, "theme.css"), theme);

const componentStylesPath = join(DIST, "style.css");
const componentStyles = readFileSync(componentStylesPath, "utf-8");
writeFileSync(componentStylesPath, `${tokens}\n${componentStyles}`);

// ── Post-emit guards ──────────────────────────────────────────────────────────
if (
  /@(theme|tailwind|apply|utility|variant|plugin|source|config|reference)\b/.test(
    stripComments(tokens),
  )
) {
  fail("dist/tokens.css must contain no Tailwind at-rule");
}
if (!/@theme\s+static\b/.test(stripComments(theme))) {
  fail("dist/theme.css must carry `@theme static`");
}

process.stdout.write(
  "[@ay/ui-library] built dist/{core,semantic,tokens,theme}.css — " +
    declaredCore.length +
    " core tokens, " +
    declaredNames(blockBody(stripComments(semantic), /:root\b[^{]*/) ?? "").length +
    " semantic tokens\n",
);
